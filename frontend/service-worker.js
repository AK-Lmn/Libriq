self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    if (IS_LOCAL_DEV) {
      self.skipWaiting();
      return;
    }
    const cache = await caches.open(CACHE_NAME);
    // cache: 'reload' skips the HTTP cache. /js/* is cached for a day, so a
    // plain addAll could store yesterday's modules next to today's.
    await cache.addAll(SHELL_ASSETS.map(asset => new Request(scopeUrl(asset), { cache: 'reload' })));
    // First install has no page to disturb. An update waits until the page
    // asks for it (Reload), so open tabs never mix modules from two deploys.
    if (!self.registration.active) self.skipWaiting();
  })());
});

self.addEventListener('message', (event) => {
  if (event.data?.type === 'SKIP_WAITING') self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    if (IS_LOCAL_DEV) {
      const keys = await caches.keys();
      await Promise.all(keys.map((key) => caches.delete(key)));
      await self.registration.unregister();
      return;
    }
    const keys = await caches.keys();
    await Promise.all(keys.map((key) => {
      if (key.startsWith('libriq-') && key !== CACHE_NAME && key !== COVER_CACHE) {
        return caches.delete(key);
      }
      return Promise.resolve(false);
    }));
    await clients.claim();
  })());
});

self.addEventListener('fetch', (event) => {
  const { request } = event;

  if (request.method !== 'GET') return;

  const url = new URL(request.url);

  // Firebase auth handler and config (proxied to firebaseapp.com by
  // vercel.json): always straight from the network, never cached.
  if (url.pathname.startsWith('/__/')) return;

  if (url.origin !== self.location.origin) {
    if (!IS_LOCAL_DEV && isCoverRequest(url)) {
      event.respondWith(coverCacheFirst(request));
      return;
    }
    if (isApiRequest(url)) {
      event.respondWith(fetch(request));
    }
    return;
  }

  if (IS_LOCAL_DEV) {
    event.respondWith(fetch(request));
    return;
  }

  if (isNavigationRequest(request)) {
    event.respondWith(handleNavigationRequest(request));
    return;
  }

  // Runtime config (Firebase, App Check, API keys) must reflect the latest deploy.
  if (isRuntimeConfig(url)) {
    event.respondWith(networkFirst(request));
    return;
  }

  if (isAppShellAsset(url)) {
    event.respondWith(cacheFirst(request));
  }
});

function isRuntimeConfig(url) {
  return /\/js\/(config|version|version-classic)\.js$/.test(url.pathname);
}

async function networkFirst(request) {
  const cache = await caches.open(CACHE_NAME);
  try {
    const response = await fetch(request, { cache: 'no-cache' });
    if (response && response.ok) {
      cache.put(request, response.clone());
    }
    return response;
  } catch {
    const cached = await cache.match(request);
    return cached || Response.error();
  }
}

function isAppShellNavigation(url) {
  const scopePath = new URL(self.registration.scope).pathname;
  return url.pathname === scopePath || url.pathname === `${scopePath}index.html`;
}

async function handleNavigationRequest(request) {
  const cache = await caches.open(CACHE_NAME);
  // The app page comes from the same deploy as the cached JS and CSS. A newer
  // index.html from the network would run against this deploy's modules.
  if (isAppShellNavigation(new URL(request.url))) {
    const shell = await cache.match(scopeUrl('./index.html'));
    if (shell) return shell;
  }
  try {
    const response = await fetch(request);
    return response;
  } catch {
    // Offline: serve the cached copy of this page (privacy.html, terms.html)
    // if there is one, and the app page otherwise.
    const page = await cache.match(request, { ignoreSearch: true });
    if (page) return page;
    const cached = await cache.match(scopeUrl('./index.html'));
    if (cached) return cached;
    return new Response('Offline', { status: 503, headers: { 'Content-Type': 'text/plain; charset=utf-8' } });
  }
}

async function cacheFirst(request) {
  const cache = await caches.open(CACHE_NAME);
  // Precache keys have no query string, but the page asks for icons and the
  // manifest with ?v=2. This cache holds one deploy, so the query adds nothing.
  const cached = await cache.match(request, { ignoreSearch: true });
  // No background refresh: this cache belongs to one deploy, and refreshing
  // it would pull the next deploy's files in one at a time.
  if (cached) return cached;

  try {
    const response = await fetch(request);
    if (response && response.ok) {
      cache.put(request, response.clone());
    }
    return response;
  } catch {
    return Response.error();
  }
}

function isNavigationRequest(request) {
  const accept = request.headers.get('accept') || '';
  return request.mode === 'navigate'
    || request.destination === 'document'
    || accept.includes('text/html');
}

// Open Library covers send Access-Control-Allow-Origin: *, also on the
// archive.org hosts they redirect to. Fetching them in CORS mode gives normal
// (not opaque) responses, so the cache costs their real size; opaque
// responses count as several MB each against the storage quota. Google
// Books covers send no CORS header, so they stay network-only.
function isCoverRequest(url) {
  return url.hostname === 'covers.openlibrary.org' && url.pathname.startsWith('/b/');
}

async function coverCacheFirst(request) {
  const cache = await caches.open(COVER_CACHE);
  const cached = await cache.match(request.url);
  if (cached) return cached;
  try {
    const response = await fetch(request.url, { mode: 'cors', credentials: 'omit' });
    // ?default=false covers answer 404 when there is no cover; the page then
    // draws its own placeholder, so only real images are kept.
    if (response.ok && response.type === 'cors') {
      await cache.put(request.url, response.clone());
      trimCoverCache(cache);
    }
    return response;
  } catch {
    return Response.error();
  }
}

async function trimCoverCache(cache) {
  const keys = await cache.keys();
  // Oldest first: Cache Storage keeps insertion order.
  await Promise.all(keys.slice(0, Math.max(0, keys.length - COVER_LIMIT)).map(key => cache.delete(key)));
}

function isAppShellAsset(url) {
  const pathname = url.pathname;
  return pathname.endsWith('.css')
    || pathname.endsWith('.js')
    || pathname.endsWith('.png')
    || pathname.endsWith('.svg')
    || pathname.endsWith('.woff2')
    || pathname.endsWith('.webmanifest')
    || pathname.endsWith('.json');
}

function isApiRequest(url) {
  return url.hostname === 'openlibrary.org' || url.hostname === 'www.googleapis.com';
}

function scopeUrl(path) {
  return new URL(path, self.registration.scope).href;
}
